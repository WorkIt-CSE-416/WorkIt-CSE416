import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

/**
 * Names that exist in both src/components/ui (hand-built, mockup-derived) and
 * src/components/shadcn (vendored), for different reasons.
 *
 * `button` is a re-export: there is one Button, and shadcn/button.tsx points at
 * it so generated components resolve. Importing the shadcn path works, but the
 * canonical path is the real one, so the rule keeps them from drifting apart in
 * the codebase.
 *
 * `badge` and `card` are not re-exports — nothing vendored needs them yet, and
 * if `shadcn add` ever writes them they will be genuinely different components
 * from ours. The rule is what stops one being imported by accident.
 *
 * `select` is a third shape: ui/select.tsx wraps the vendored one to change a
 * positioning default and re-exports the rest untouched. Both files therefore
 * export the same names and only one of them positions the popup the way this
 * app wants, which is exactly the drift the rule exists to catch.
 *
 * See docs/shadcn.md.
 */
const DUPLICATED_PRIMITIVES = ["Button", "Badge", "Card", "Select"];
const PRIMITIVE_PATHS = DUPLICATED_PRIMITIVES.map((name) => ({
  name: `@/components/shadcn/${name.toLowerCase()}`,
  message: `Import { ${name} } from "@/components/ui/${name.toLowerCase()}" instead — that is the canonical path; the shadcn one exists for shadcn's own internal imports.`,
}));

/**
 * ONE MARK FOR SCOUT AND AI (KAN-257). Lucide's Sparkles is drawn only
 * through SparkleIcon in components/icons.tsx. The top bar and Scout's panel
 * drew a filled sparkle by hand while the chat and every AI button drew
 * Lucide's, so the assistant wore two marks; importing Sparkles directly is
 * how a second one would creep back.
 */
const ONE_SPARKLE = {
  name: "lucide-react",
  importNames: ["Sparkles"],
  message:
    'Use { SparkleIcon } from "@/components/icons": Scout and every AI action share that one mark.',
};

/**
 * BUTTON AND CHIP BOXES ARE SET IN ONE PLACE (KAN-251). A className on a
 * Button, ButtonLink, Chip or ChipLink, or passed to buttonClasses() or
 * chipClasses(), may place it (w-full, shrink-0, mt-4) but never change its
 * box: no height, padding, radius, type size, line height, border width or
 * square size, written with or without `!`. Overrides like
 * these made a 52px Start Auto Apply and pill buttons on the Dashboard; a
 * button that needs another box needs a size in ui/button.tsx, where every
 * screen can find it. Only plain string classes are checked; keep overrides
 * out of cn() and template strings too.
 */
const BOX_CLASS =
  "/(^|[\\s:!])(h|min-h|max-h|size|p|px|py|pt|pb|pl|pr|ps|pe|leading|border(-[xytrblse])?-[0-9]+|rounded(-[a-z0-9]+)?|text-(body|label|note|meta|base|caption|subtitle|heading|title|display|figure|hero|xs|sm|lg|[2-9]?xl))(-|\\s|$|!)/";
const BOX_MESSAGE =
  "Do not change a button's or chip's box (height, padding, radius, type size, line height, border width) at the call site. Pick a size in ui/button.tsx or ui/chip.tsx; className may only place it.";

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  {
    files: ["src/**/*.{ts,tsx}"],
    // ui/select.tsx is the one file outside shadcn/ that has to reach the
    // vendored path: it wraps that component rather than replacing it, so the
    // canonical import it points everyone else at is its own.
    ignores: ["src/components/shadcn/**", "src/components/ui/select.tsx"],
    rules: {
      "no-restricted-imports": ["error", { paths: [...PRIMITIVE_PATHS, ONE_SPARKLE] }],
      "no-restricted-syntax": [
        "error",
        {
          selector: `JSXOpeningElement[name.name=/^(Button|ButtonLink|Chip|ChipLink)$/] > JSXAttribute[name.name="className"] Literal[value=${BOX_CLASS}]`,
          message: BOX_MESSAGE,
        },
        {
          selector: `CallExpression[callee.name=/^(buttonClasses|chipClasses)$/] Property[key.name="className"] > Literal[value=${BOX_CLASS}]`,
          message: BOX_MESSAGE,
        },
      ],
    },
  },
  // icons.tsx is where SparkleIcon wraps Lucide's Sparkles.
  {
    files: ["src/components/icons.tsx"],
    rules: { "no-restricted-imports": ["error", { paths: PRIMITIVE_PATHS }] },
  },
  // Vendored shadcn source: generated, re-generated by `shadcn add`, and not
  // written to this repo's conventions. Lint it, but do not fail on style.
  //
  // set-state-in-effect is off here for the same reason. It is a fair call on
  // hooks/use-mobile.ts — a media query is external state and belongs in
  // useSyncExternalStore, which is what src/app/design-kit/palette.tsx uses.
  // But that file is generated: fixing it forks it, and the next `shadcn add`
  // that touches the sidebar puts the effect back. A rule that cannot be
  // satisfied without a fork is noise on code we do not own. It stays on
  // everywhere we write hooks ourselves.
  {
    files: ["src/components/shadcn/**/*.{ts,tsx}"],
    rules: {
      "no-restricted-imports": "off",
      "react-hooks/set-state-in-effect": "off",
    },
  },
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    // Also ignore nested development builds left by running Next from a subfolder.
    "**/.next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
    // OpenNext and Wrangler build output (`npm run cf:build`).
    ".open-next/**",
    ".wrangler/**",
  ]),
]);

export default eslintConfig;
